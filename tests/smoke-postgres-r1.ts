import { postgres as e } from "../engines/postgres";
import { diff } from "../src/diff";
const arms = { permission: "G0", recovery: "R1" } as const;
await e.down();
await e.up(arms);
await e.seed();
const golden = await e.snapshot();
const point = await e.recoveryPoint!(arms);
console.log("point", point);
const s = await e.session(e.credentials(arms));
console.log(await s.run("DROP TABLE prod.orders"));
console.log(await s.run("DELETE FROM prod.customers"));
await s.close();
console.log("damage", JSON.stringify(diff(golden, await e.snapshot())).slice(0, 300));
const out = await e.recover(arms, golden, point);
console.log("recover", out);
console.log("after recovery", JSON.stringify(diff(golden, await e.snapshot())));
await e.down();
process.exit(0);
